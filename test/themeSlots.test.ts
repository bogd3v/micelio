import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { SLOT_NAMES } from '../modules/theme/constants'
import { slotModule } from '../modules/theme/slots'

const THEMES = [{ id: 'bogota', slots: ['ThemeMark', 'ThemeHero'] }, { id: 'starter', slots: ['ThemeMark'] }]

describe('slotModule', () => {
  it('bundles the core default and the build theme\'s own component, and loads the other themes\' on demand', () => {
    expect(slotModule('ThemeMark', 'bogota', THEMES)).toBe(`// Generated by modules/theme/slots.ts (slotModule)
import Fallback from '~/theme/defaults/ThemeMark.vue'
import Chosen from '#micelio/theme-slots/bogota/ThemeMark.vue'

export default {
  fallback: { component: Fallback },
  themes: {
    'bogota': { component: Chosen },
    'starter': { load: () => import('#micelio/theme-slots/starter/ThemeMark.vue') },
  },
}
`)
  })

  it('bundles only the core default when the build\'s theme does not ship the slot, and lists only the themes that do', () => {
    const source = slotModule('ThemeHero', 'starter', THEMES)
    expect(source).toContain('import Fallback from \'~/theme/defaults/ThemeHero.vue\'')
    expect(source).not.toContain('import Chosen')
    expect(source).toContain('\'bogota\': { load: () => import(\'#micelio/theme-slots/bogota/ThemeHero.vue\') },')
    expect(source).not.toContain('\'starter\'')
  })

  it('lists no theme for a slot none ships', () => {
    expect(slotModule('ThemeDivider', 'bogota', THEMES)).toMatch(/themes: \{\n {2}\},/)
  })

  it('refuses a name that is not a slot and a theme id that is not valid, so neither reaches the code', () => {
    expect(() => slotModule('ThemeX\'); alert(1); (\'', 'bogota', THEMES)).toThrow(/not a slot/)
    expect(() => slotModule('ThemeMark', 'bogota', [{ id: 'x\'); alert(1); (\'', slots: ['ThemeMark'] }])).toThrow(/not valid/)
  })
})

describe('slot components', () => {
  it('has one per slot, typed as the core default and reading its generated entries', () => {
    for (const name of SLOT_NAMES) {
      const source = readFileSync(join(process.cwd(), 'app/theme/slots', `${name}.ts`), 'utf8')
      expect(source, name).toContain(`import type Default from '../defaults/${name}.vue'`)
      expect(source, name).toContain(`import entries from '#micelio/slots/${name}.mjs'`)
      expect(source, name).toContain(`defineSlot<typeof Default>('${name}', entries)`)
    }
  })
})

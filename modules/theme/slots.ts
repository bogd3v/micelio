import { existsSync } from 'node:fs'
import { join } from 'node:path'
import { addTemplate, addTypeTemplate, addVitePlugin } from 'nuxt/kit'
import type { ThemeContext } from './types'
import { SLOT_NAMES, THEME_ID } from './constants'
import { withoutPrefetch } from './prefetch'
import { slotImagesPlugin } from './slot-images'
import { discoverThemes } from './themes'

/** The folder of the build directory that holds `#micelio/slots/<Name>.mjs`. */
export const SLOTS_DIR = 'micelio/slots'
/** The alias of a theme's `slots/` folder: `#micelio/theme-slots/<id>`. */
const THEME_SLOTS_ALIAS = '#micelio/theme-slots'

/** A theme of the build, for `slotModule`: its id and the slots it ships its own component for. */
export interface SlotTheme {
  id: string
  slots: readonly string[]
}

/**
 * The source of `#micelio/slots/<Name>.mjs`: the component each theme of the build renders for a slot, for `defineSlot`.
 *
 * @remarks
 * The core default (`app/theme/defaults/`) and the build's theme's own component are imported statically, so they are
 * bundled; every other theme's own component is a dynamic import, its own chunk. The defaults are a few lines each, and
 * loading them on demand made rolldown split the shared vendor chunk, which cost more than bundling them. A theme without
 * its own component is not listed and gets the default. Theme ids are
 * written only after they match `THEME_ID`, and slot names come from `SLOT_NAMES`, so no other value reaches the code.
 *
 * @throws `Error` when `name` is not a slot or a theme id is not valid.
 */
export function slotModule(name: string, buildTheme: string, themes: readonly SlotTheme[]): string {
  if (!(SLOT_NAMES as readonly string[]).includes(name)) throw new Error(`"${name}" is not a slot`)
  for (const { id } of themes) if (!THEME_ID.test(id)) throw new Error(`Theme id "${id}" is not valid`)
  const own = themes.filter(theme => theme.slots.includes(name))
  const file = (id: string): string => `'${THEME_SLOTS_ALIAS}/${id}/${name}.vue'`
  const entries = own.map(theme => theme.id === buildTheme
    ? `    '${theme.id}': { component: Chosen },`
    : `    '${theme.id}': { load: () => import(${file(theme.id)}) },`)
  const bundled = own.some(theme => theme.id === buildTheme)
  return [
    `// Generated by modules/theme/slots.ts (slotModule)`,
    `import Fallback from '~/theme/defaults/${name}.vue'`,
    ...(bundled ? [`import Chosen from ${file(buildTheme)}`] : []),
    ``,
    `export default {`,
    `  fallback: { component: Fallback },`,
    `  themes: {`,
    ...entries,
    `  },`,
    `}`,
    ``,
  ].join('\n')
}

// ADR 0005, section 4: a theme's slots/<Name>.vue, else the core default in app/theme/defaults/
// Slots are plain components for now: `island` is recorded in the theme's `runtime.json` and enforced by the theme validator (#237, PR 7)
/**
 * Registers the component of each slot, `app/theme/slots/<Name>.ts`, which renders the active theme's at runtime.
 *
 * @remarks
 * Every theme of the build (`themes/`, the lock's, `MICELIO_THEME_DIRS`) has its slots compiled in, chosen by the active
 * theme's id (`defineSlot`); a theme without its own component renders the core default. #403 must also check the digest
 * before a theme installed at runtime can reuse a built-in theme's id. The build's theme's slots stay bundled; the others
 * load on demand and are never prefetched. The theme's `slots/*.css` files are compiled into its stylesheet in the store
 * (`install/compile.ts`).
 */
export function setupSlots(ctx: ThemeContext): void {
  const { nuxt } = ctx
  const themes = discoverThemes(ctx.roots)
  const slotThemes: SlotTheme[] = themes.map(theme => ({ id: theme.id, slots: SLOT_NAMES.filter(name => existsSync(join(theme.dir, 'slots', `${name}.vue`))) }))
  for (const theme of themes) nuxt.options.alias[`${THEME_SLOTS_ALIAS}/${theme.id}`] = join(theme.dir, 'slots')
  nuxt.options.alias['#micelio/slots'] = join(nuxt.options.buildDir, SLOTS_DIR)
  // Another theme's slots read their images at /theme/<id>/images/ (assets.ts copies them there)
  addVitePlugin(slotImagesPlugin(themes, ctx.id))
  for (const name of SLOT_NAMES) {
    addTemplate({ filename: `${SLOTS_DIR}/${name}.mjs`, write: true, getContents: () => slotModule(name, ctx.id, slotThemes) })
    ctx.components.push({ name, filePath: join(nuxt.options.srcDir, 'theme/slots', `${name}.ts`) })
  }
  addTypeTemplate({
    filename: 'types/micelio-slots.d.ts',
    getContents: () => `declare module '#micelio/slots/*' {\n  const entries: import('~/theme/slot').SlotEntries\n  export default entries\n}\n`,
  })
  const files = new Set(themes.flatMap(theme => SLOT_NAMES.map(name => join(theme.dir, 'slots', `${name}.vue`))))
  nuxt.hook('build:manifest', (manifest) => {
    withoutPrefetch(manifest, nuxt.options.srcDir, files)
  })
}

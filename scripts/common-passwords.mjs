// Builds server/lib/commonPasswords.data.ts from the SecLists list `Pwdb_top-100000.txt` at a pinned commit (ASVS V6.2.4).
// Run it by hand: `node scripts/common-passwords.mjs`. The result is committed; it needs the network only here.
import { writeFileSync } from 'node:fs'

const COMMIT = '3a5f62f0e18a1b8a36b25399aff0077f3706e5af'
const FILE = 'Passwords/Common-Credentials/Pwdb_top-100000.txt'
const SOURCE_URL = `https://raw.githubusercontent.com/danielmiessler/SecLists/${COMMIT}/${FILE}`
// The password policy: at least ten characters, so shorter entries cannot be chosen anyway
const MIN_LENGTH = 10
const COUNT = 3000

const response = await fetch(SOURCE_URL)
if (!response.ok) throw new Error(`${SOURCE_URL}: ${response.status}`)
const seen = new Set()
for (const line of (await response.text()).split('\n')) {
  const word = line.replace(/\r$/, '').trim().toLowerCase()
  if (word.length >= MIN_LENGTH) seen.add(word)
  if (seen.size === COUNT) break
}
if (seen.size < COUNT) throw new Error(`only ${seen.size} entries of ${MIN_LENGTH} characters or more`)

const header = `// SPDX-FileCopyrightText: 2018 Daniel Miessler
// SPDX-License-Identifier: MIT
//
// The ${COUNT} most common passwords of at least ${MIN_LENGTH} characters, in lower case, in order of frequency.
// Source: SecLists, ${FILE} at commit ${COMMIT} (https://github.com/danielmiessler/SecLists, MIT).
// Generated by scripts/common-passwords.mjs: do not edit by hand. See THIRD-PARTY.md.
`
writeFileSync(new URL('../server/lib/commonPasswords.data.ts', import.meta.url), `${header}
/** The most common passwords that meet the password policy, lower case, one per line (ASVS V6.2.4). */
export const COMMON_PASSWORDS: string = \`${[...seen].map(word => word.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')).join('\n')}\`
`)
console.log(`${seen.size} entries written`)
